export const CROP_NAME_TO_ASSET: Record<string, CropAssetItem> = {};
Object.values(CROP_ASSETS).forEach((item) => {
  CROP_NAME_TO_ASSET[item.name.toLowerCase().trim()] = item;
  // Alias hoa thường
  if (item.name === 'Hoa xương Rồng Cholla') {
    CROP_NAME_TO_ASSET['hoa xương rồng cholla'] = item;
  }
});

export function getCropImageByName(name: string): string {
  const item = CROP_NAME_TO_ASSET[name.toLowerCase().trim()];
  return item ? item.icon : '';
}

export function getCropPngByName(name: string): string {
  const item = CROP_NAME_TO_ASSET[name.toLowerCase().trim()];
  return item ? item.iconPng : '';
}

export function getCropEmojiByName(name: string): string {
  const item = CROP_NAME_TO_ASSET[name.toLowerCase().trim()];
  return item ? item.emoji : '🍎';
}
